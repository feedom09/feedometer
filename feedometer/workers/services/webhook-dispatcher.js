/**
 * Compute HMAC-SHA256 signature string for a webhook payload
 */
export async function generateHmacSignature(secretKey, payloadString) {
  const enc = new TextEncoder();
  const keyData = enc.encode(secretKey || '');
  const key = await crypto.subtle.importKey(
    'raw',
    keyData,
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign']
  );
  const signatureBuffer = await crypto.subtle.sign('HMAC', key, enc.encode(payloadString || ''));
  const hashArray = Array.from(new Uint8Array(signatureBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

/**
 * Calculates the next UTC timestamp for a scheduled webhook based on cadence and time.
 *
 * @param {string} cadence - 'daily' | 'weekly' | 'realtime'
 * @param {string} scheduleTime - "HH:MM" in 24-hour UTC (e.g. "17:00", "09:00")
 * @param {string} scheduleDay - 'monday'..'sunday'
 * @param {Date|number|string} [fromDate] - Reference date (defaults to new Date())
 * @returns {number} UTC epoch timestamp in milliseconds
 */
export function calculateNextWebhookRun(cadence = 'daily', scheduleTime = '17:00', scheduleDay = 'monday', fromDate = new Date()) {
  const now = fromDate instanceof Date ? fromDate : new Date(fromDate);
  const [hoursStr, minutesStr] = (scheduleTime || '17:00').split(':');
  const targetHour = parseInt(hoursStr || '17', 10);
  const targetMin = parseInt(minutesStr || '0', 10);

  if (cadence === 'daily') {
    const next = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate(), targetHour, targetMin, 0, 0));
    if (next.getTime() <= now.getTime()) {
      next.setUTCDate(next.getUTCDate() + 1);
    }
    return next.getTime();
  }

  if (cadence === 'weekly') {
    const daysMap = { sunday: 0, monday: 1, tuesday: 2, wednesday: 3, thursday: 4, friday: 5, saturday: 6 };
    const targetDayIndex = daysMap[(scheduleDay || 'monday').toLowerCase()] ?? 1;
    const currentDayIndex = now.getUTCDay();

    let dayDiff = targetDayIndex - currentDayIndex;
    if (dayDiff < 0 || (dayDiff === 0 && (now.getUTCHours() > targetHour || (now.getUTCHours() === targetHour && now.getUTCMinutes() >= targetMin)))) {
      dayDiff += 7;
    }

    const next = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + dayDiff, targetHour, targetMin, 0, 0));
    return next.getTime();
  }

  return 0; // realtime
}

/**
 * Formats a batched list of articles into Slack Block Kit card structure
 */
export function buildSlackBlockKitPayload(webhookOrOptions = {}, articlesList = [], periodLabel = '') {
  let webhook = {};
  let articles = [];

  if (Array.isArray(articlesList) && articlesList.length > 0) {
    webhook = webhookOrOptions || {};
    articles = articlesList;
  } else if (webhookOrOptions && Array.isArray(webhookOrOptions.articles)) {
    webhook = webhookOrOptions;
    articles = webhookOrOptions.articles;
  } else {
    webhook = webhookOrOptions || {};
    articles = [];
  }

  const name = webhook.name || 'FeedOmeter News Digest';
  const cadence = webhook.cadence || 'daily';
  const scheduleTime = webhook.schedule_time || '17:00';
  const count = articles.length;
  const timeLabel = cadence === 'weekly' ? 'Weekly Digest' : `Daily Digest (${scheduleTime})`;
  const mainHeader = `📰 *${name}*`;

  const blocks = [
    {
      type: 'header',
      text: {
        type: 'plain_text',
        text: `📰 ${name}`,
        emoji: true
      }
    },
    {
      type: 'context',
      elements: [
        {
          type: 'mrkdwn',
          text: `📅 *Schedule:* ${timeLabel} • *Articles:* ${count} • Generated by *FeedOmeter*`
        }
      ]
    },
    { type: 'divider' }
  ];

  if (count === 0) {
    blocks.push({
      type: 'section',
      text: {
        type: 'mrkdwn',
        text: '_No new matching articles syndicated during this digest period._'
      }
    });
  } else {
    // Cap at top 15 articles to stay within Slack's 50 block limit
    const displayList = articles.slice(0, 15);
    displayList.forEach((art, idx) => {
      const title = (art.title || 'Untitled Article').replace(/[<>&]/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c]));
      const url = art.url || art.link || 'https://feedometer.com';
      const source = art.source_name || art.source || art.domain || 'News Source';
      const snippet = (art.description || art.snippet || art.content_snippet || '').replace(/<[^>]+>/g, '').trim().slice(0, 160);
      const img = art.image_url || art.image || art.og_image || '';

      const sectionBlock = {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*<${url}|${idx + 1}. ${title}>*\n*${source}* • ${snippet ? `_${snippet}..._` : ''}`
        }
      };

      if (img && (img.startsWith('http://') || img.startsWith('https://'))) {
        sectionBlock.accessory = {
          type: 'image',
          image_url: img,
          alt_text: 'article thumbnail'
        };
      }

      blocks.push(sectionBlock);
    });

    if (articles.length > 15) {
      blocks.push({
        type: 'context',
        elements: [
          {
            type: 'mrkdwn',
            text: `_...and ${articles.length - 15} more articles matching your filters._`
          }
        ]
      });
    }
  }

  blocks.push({ type: 'divider' });

  return {
    text: `${mainHeader} — ${count} articles matched`,
    blocks
  };
}

/**
 * Formats a standard JSON batch envelope for scheduled webhooks
 */
export function buildStandardBatchPayload(webhookOrOptions = {}, articlesList = [], periodParam = {}) {
  let webhook = {};
  let articles = [];
  let period = {};

  if (Array.isArray(articlesList)) {
    webhook = webhookOrOptions || {};
    articles = articlesList;
    period = typeof periodParam === 'string' ? { from: periodParam, to: new Date().toISOString() } : (periodParam || {});
  } else if (webhookOrOptions && typeof webhookOrOptions === 'object') {
    webhook = webhookOrOptions.webhook || webhookOrOptions;
    articles = webhookOrOptions.articles || [];
    period = webhookOrOptions.period || {};
  }

  const fromIso = period.from ? new Date(period.from).toISOString() : new Date(Date.now() - 86400000).toISOString();
  const toIso = period.to ? new Date(period.to).toISOString() : new Date().toISOString();

  return {
    event: 'digest.webhook.batch',
    webhook_id: webhook.id || 'test-wh',
    webhook_name: webhook.name || 'Webhook Digest',
    cadence: webhook.cadence || 'daily',
    scheduled_time: webhook.schedule_time || '17:00',
    period: {
      from: fromIso,
      to: toIso
    },
    count: articles.length,
    total_articles: articles.length,
    since: fromIso,
    articles: articles.map(a => ({
      id: a.id || a.article_id,
      title: a.title,
      url: a.url || a.link,
      source_name: a.source_name || a.source || a.domain || '',
      published_at: a.published_at || a.created_at || Date.now(),
      snippet: (a.description || a.snippet || a.content_snippet || '').replace(/<[^>]+>/g, '').trim().slice(0, 300),
      image_url: a.image_url || a.image || ''
    }))
  };
}

/**
 * Atomically claim pending real-time webhook delivery tasks
 */
export async function claimPendingWebhookDeliveries(env, limit = 15, lockDurationMs = 60000) {
  if (!env.DB) return [];
  const now = Date.now();
  const lockExpires = now + lockDurationMs;

  try {
    const candidates = await env.DB.prepare(`
      SELECT wd.id, wd.webhook_id, wd.article_id, wd.payload_json, wd.attempt_count,
             uw.target_url, uw.secret_key
      FROM webhook_deliveries wd
      JOIN user_webhooks uw ON uw.id = wd.webhook_id
      WHERE (wd.status = 'pending' OR (wd.status = 'processing' AND wd.locked_until < ?))
        AND wd.attempt_count < 3
        AND uw.is_active = 1
      ORDER BY wd.created_at ASC
      LIMIT ?
    `).bind(now, limit).all();

    const rows = candidates.results || [];
    if (rows.length === 0) return [];

    const ids = rows.map(r => r.id);
    const placeholders = ids.map(() => '?').join(',');

    await env.DB.prepare(`
      UPDATE webhook_deliveries 
      SET status = 'processing', locked_until = ?
      WHERE id IN (${placeholders})
    `).bind(lockExpires, ...ids).run();

    return rows;
  } catch (err) {
    console.error('Error claiming webhook deliveries:', err.message);
    return [];
  }
}

/**
 * Dispatches a single webhook delivery with timeout and telemetry logging
 */
export async function executeSingleWebhookDelivery(env, delivery, { fetchImpl = fetch } = {}) {
  const startTime = Date.now();
  const payloadStr = typeof delivery.payload_json === 'string' 
    ? delivery.payload_json 
    : JSON.stringify(delivery.payload_json);

  let responseCode = 0;
  let responseBody = '';
  let errorMsg = null;
  let success = false;

  try {
    const targetValidation = normalizeExternalHttpUrl(delivery.target_url);
    if (!targetValidation.ok) throw new Error(targetValidation.message);
    const signature = await generateHmacSignature(delivery.secret_key, payloadStr);
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000);

    const response = await fetchImpl(targetValidation.url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'User-Agent': 'FeedOmeter-Webhook/2.1 (+https://feedometer.com)',
        'X-Feedometer-Signature-256': signature,
        'X-Feedometer-Event': eventTypeFromPayload(payloadStr),
        'X-Feedometer-Delivery-ID': delivery.id
      },
      body: payloadStr,
      signal: controller.signal
    });

    clearTimeout(timeoutId);
    responseCode = response.status;
    const rawText = await response.text();
    responseBody = rawText.slice(0, 500);

    if (response.ok) {
      success = true;
    } else {
      errorMsg = `HTTP Error ${response.status}: ${response.statusText}`;
    }
  } catch (err) {
    errorMsg = err.name === 'AbortError' ? 'Webhook delivery timed out after 6000ms' : err.message;
    responseCode = 0;
  }

  const durationMs = Date.now() - startTime;
  const now = Date.now();
  const nextAttemptCount = (delivery.attempt_count || 0) + 1;

  if (success) {
    await env.DB.prepare(`
      UPDATE webhook_deliveries 
      SET status = 'delivered', response_code = ?, response_body = ?, duration_ms = ?, delivered_at = ?, locked_until = 0
      WHERE id = ?
    `).bind(responseCode, responseBody, durationMs, now, delivery.id).run();
  } else {
    const finalStatus = nextAttemptCount >= 3 ? 'failed' : 'pending';
    await env.DB.prepare(`
      UPDATE webhook_deliveries 
      SET status = ?, attempt_count = ?, response_code = ?, response_body = ?, duration_ms = ?, locked_until = 0
      WHERE id = ?
    `).bind(finalStatus, nextAttemptCount, responseCode, errorMsg || responseBody, durationMs, delivery.id).run();
  }

  return { success, responseCode, durationMs, errorMsg };
}

/**
 * Dispatch a batch of pending real-time webhook deliveries
 */
export async function dispatchWebhookBatch(env, limit = 15) {
  if (!env.DB) return { delivered: 0, failed: 0 };
  const claimed = await claimPendingWebhookDeliveries(env, limit);
  if (claimed.length === 0) return { delivered: 0, failed: 0 };

  const results = await Promise.allSettled(
    claimed.map(item => executeSingleWebhookDelivery(env, item))
  );

  let delivered = 0;
  let failed = 0;
  results.forEach(r => {
    if (r.status === 'fulfilled' && r.value.success) delivered++;
    else failed++;
  });

  return { total: claimed.length, delivered, failed };
}

/**
 * Process all due Scheduled Webhooks (Cadence == 'daily' | 'weekly')
 */
export async function processScheduledWebhooks(env) {
  if (!env.DB) return { processed: 0, delivered: 0, failed: 0 };

  const now = Date.now();
  try {
    const dueWebhooksRes = await env.DB.prepare(`
      SELECT uw.*
      FROM user_webhooks uw
      WHERE uw.is_active = 1
        AND uw.cadence != 'realtime'
        AND (uw.next_run_at <= ? OR uw.next_run_at = 0)
    `).bind(now).all();

    const dueWebhooks = dueWebhooksRes.results || [];
    if (dueWebhooks.length === 0) return { processed: 0, delivered: 0, failed: 0 };

    let deliveredCount = 0;
    let failedCount = 0;

    for (const webhook of dueWebhooks) {
      const windowStart = webhook.last_cursor_at > 0 
        ? webhook.last_cursor_at 
        : (webhook.cadence === 'weekly' ? now - (7 * 86400000) : now - 86400000);

      // Fetch user's candidate articles syndicated during this window
      const articlesRes = await env.DB.prepare(`
        SELECT a.id, a.title, a.link, a.description, a.published_at, a.image_url,
               s.title as source_name, s.website_url, s.feed_url
        FROM user_feeds uf
        JOIN sources s ON s.id = uf.source_id
        JOIN articles a ON a.source_id = s.id
        WHERE uf.user_id = ?
          AND a.published_at > ?
          AND a.published_at <= ?
        ORDER BY a.published_at DESC
        LIMIT 100
      `).bind(webhook.user_id, windowStart, now).all();

      let ruleConfig = {};
      try { ruleConfig = JSON.parse(webhook.config_json || '{}'); } catch (_) {}

      // Filter articles using Universal Rule Engine
      const matchedArticles = filterArticlesByRule(articlesRes.results || [], ruleConfig);

      // Construct payload
      let payloadObj;
      if (webhook.format_type === 'slack') {
        payloadObj = buildSlackBlockKitPayload({
          name: webhook.name,
          webhookId: webhook.id,
          cadence: webhook.cadence,
          scheduleTime: webhook.schedule_time,
          period: { from: windowStart, to: now },
          articles: matchedArticles
        });
      } else {
        payloadObj = buildStandardBatchPayload({
          webhook,
          period: { from: windowStart, to: now },
          articles: matchedArticles
        });
      }

      const payloadStr = JSON.stringify(payloadObj);
      const signature = await generateHmacSignature(webhook.secret_key, payloadStr);
      const deliveryId = `whd_${generateRandomHex(12)}`;
      const startTime = Date.now();

      let responseCode = 0;
      let responseBody = '';
      let success = false;

      try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 8000);

        const res = await fetch(webhook.target_url, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'User-Agent': 'FeedOmeter-Webhook/2.1 (+https://feedometer.com)',
            'X-Feedometer-Signature-256': signature,
            'X-Feedometer-Event': 'digest.webhook.batch',
            'X-Feedometer-Delivery-ID': deliveryId
          },
          body: payloadStr,
          signal: controller.signal
        });

        clearTimeout(timeoutId);
        responseCode = res.status;
        responseBody = (await res.text()).slice(0, 500);
        success = res.ok;
      } catch (e) {
        responseBody = e.message;
      }

      const durationMs = Date.now() - startTime;

      // Log delivery record
      await env.DB.prepare(`
        INSERT INTO webhook_deliveries (id, webhook_id, article_id, payload_json, status, attempt_count, response_code, response_body, duration_ms, delivered_at, created_at)
        VALUES (?, ?, 'batch', ?, ?, 1, ?, ?, ?, ?, ?)
      `).bind(
        deliveryId,
        webhook.id,
        payloadStr,
        success ? 'delivered' : 'failed',
        responseCode,
        responseBody,
        durationMs,
        success ? Date.now() : null,
        now
      ).run().catch(() => {});

      // Calculate next run & advance cursor
      const nextRunAt = calculateNextWebhookRun(webhook.cadence, webhook.schedule_time, webhook.schedule_day);
      await env.DB.prepare(`
        UPDATE user_webhooks 
        SET last_cursor_at = ?, next_run_at = ?
        WHERE id = ?
      `).bind(now, nextRunAt, webhook.id).run();

      if (success) deliveredCount++;
      else failedCount++;
    }

    return { processed: dueWebhooks.length, delivered: deliveredCount, failed: failedCount };
  } catch (err) {
    console.error('Error processing scheduled webhooks:', err.message);
    return { processed: 0, delivered: 0, failed: 0, error: err.message };
  }
}

/**
 * Test an arbitrary webhook endpoint with an instant verification ping or sample Slack card
 */
export async function testWebhookEndpoint(targetUrl, secretKey, formatType = 'standard') {
  const targetValidation = normalizeExternalHttpUrl(targetUrl);
  if (!targetValidation.ok) {
    return { ok: false, status: 0, statusText: targetValidation.code, durationMs: 0, responsePreview: targetValidation.message };
  }
  const startTime = Date.now();
  let testPayload;

  if (formatType === 'slack') {
    testPayload = JSON.stringify(buildSlackBlockKitPayload({
      name: 'FeedOmeter Test Webhook',
      webhookId: 'test_whk',
      cadence: 'daily',
      scheduleTime: '17:00',
      period: { from: startTime - 86400000, to: startTime },
      articles: [
        {
          title: 'OpenAI Unveils Breakthrough AI Agent Paradigm',
          url: 'https://feedometer.com',
          source_name: 'TechCrunch',
          snippet: 'Live sample article verifying that your Slack channel receives native interactive cards with thumbnails and links properly.',
          image_url: 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?w=400'
        }
      ]
    }));
  } else {
    testPayload = JSON.stringify({
      event: 'endpoint.verified',
      timestamp: startTime,
      message: 'Hello from FeedOmeter Webhook Dispatcher! Your endpoint is verified and ready.',
      source: 'FeedOmeter Automation Engine'
    });
  }

  try {
    const signature = await generateHmacSignature(secretKey, testPayload);
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000);

    const res = await fetch(targetValidation.url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'User-Agent': 'FeedOmeter-Webhook/2.1 (+https://feedometer.com)',
        'X-Feedometer-Signature-256': signature,
        'X-Feedometer-Event': formatType === 'slack' ? 'digest.webhook.batch' : 'endpoint.verified'
      },
      body: testPayload,
      signal: controller.signal
    });

    clearTimeout(timeoutId);
    const durationMs = Date.now() - startTime;
    const body = (await res.text()).slice(0, 300);

    return {
      ok: res.ok,
      status: res.status,
      statusText: res.statusText,
      durationMs,
      responsePreview: body
    };
  } catch (err) {
    return {
      ok: false,
      status: 0,
      statusText: err.name === 'AbortError' ? 'Connection timed out (6s)' : err.message,
      durationMs: Date.now() - startTime,
      error: err.message
    };
  }
}
